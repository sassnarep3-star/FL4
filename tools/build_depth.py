#!/usr/bin/env python3
"""Build the depth/ section (session f51d93e6): route census, slot model, flags.

Reads only data/depth/*.json. Writes depth/*.html. Run tools/check_depth.py first;
this builder refuses to write if the checker fails.
"""
import html
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "depth"
D = ROOT / "data/depth"


def esc(v):
    return html.escape("" if v is None else str(v), quote=True)


def link(url, label=None):
    if not url:
        return "<em>none</em>"
    return f'<a href="{esc(url)}" target="_blank" rel="noopener">{esc(label or url)}</a>'


def table(headers, rows):
    head = "".join(f"<th>{esc(h)}</th>" for h in headers)
    body = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f'<div class="table-wrap"><table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table></div>'


def page(title, body, active):
    nav = [("../index.html", "Dashboard"), ("index.html", "Depth overview"),
           ("route-census.html", "Route census"), ("slot-model.html", "Slot model"),
           ("flags.html", "Flagged for review")]
    navhtml = " · ".join(
        (f'<strong>{esc(t)}</strong>' if h == active else f'<a href="{h}">{esc(t)}</a>') for h, t in nav)
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{esc(title)} · Depth section</title>
<link rel="stylesheet" href="../assets/style.css">
</head><body>
<header><h1>{esc(title)}</h1><nav class="subnav">{navhtml}</nav></header>
<main>{body}</main>
<footer><p>Generated by <code>tools/build_depth.py</code> from <code>data/depth/*.json</code>. Information only, not betting, legal or financial advice. Verified against the official source links shown; blank or "not checked" means not confirmed.</p></footer>
</body></html>
"""


def gate_line(gate):
    return (f"<p><strong>Gate {esc(gate['id'])}: {esc(gate['status'].upper())}</strong> — "
            f"{gate['clubs_verified_official']} of {gate['clubs_required']} clubs verified official. "
            f"{esc(gate['consequence'])}</p>")


def main():
    subprocess.run([sys.executable, str(ROOT / "tools/check_depth.py")], check=True)
    census = json.loads((D / "route_census.json").read_text())
    model = json.loads((D / "slot_model.json").read_text())
    flags = json.loads((D / "flags.json").read_text())
    OUT.mkdir(exist_ok=True)
    gate = census["gate"]

    checked_rows = [r for r in census["rows"] if r["check"] == "checked"]
    overview = f"""
<section class="callout bad"><div class="callout-title">Depth ordering is not yet a verified input</div>
<div>{gate_line(gate)}</div></section>
<section><h2>What this section shows</h2>
<ul>
<li><strong>Route census:</strong> 32 clubs, one row each. {len(checked_rows)} checked, {32 - len(checked_rows)} not checked.</li>
<li><strong>Slot model:</strong> the rules for how depth is stored (groups, shared and empty slots, no jersey-number ordering, roster-event versioning). It holds zero depth rows.</li>
<li><strong>Flags:</strong> {len(flags['flags'])} items for review, including two publishers that label their depth charts unofficial.</li>
</ul></section>
<section><h2>Why it matters</h2>
<p>The brief asks the system to know when a backup replaces a starter. That needs a depth order from a source the owner accepts. The gate above stays closed until every club's route is verified.</p></section>
"""
    (OUT / "index.html").write_text(page("Depth section — overview", overview, "Depth overview"))

    rows = []
    for r in census["rows"]:
        rows.append([
            esc(r["abbr"]), esc(r["club"]),
            "checked" if r["check"] == "checked" else "<em>not checked</em>",
            esc(r.get("http_result") or "—"),
            esc(r.get("format") or "—"),
            esc(r.get("publisher_label") or "—"),
            esc(r["authority"]),
            link(r.get("source_url"), "page") if r.get("source_url") else "<em>none</em>",
        ])
    census_html = f"""
<section>{gate_line(gate)}
<p>Each row lists what was read on 2026-11-16. A "not checked" row has no value. Authority reflects the publisher's own wording (DS-7 in the slot model).</p>
{table(["Club", "Name", "Check", "Fetch result", "Format", "Publisher label", "Authority", "Source"], rows)}
</section>"""
    (OUT / "route-census.html").write_text(page("Depth route census (32 clubs)", census_html, "Route census"))

    rules = [[esc(r["id"]), esc(r["rule"]), esc(r["why"])] for r in model["rules"]]
    gates = [[esc(g["id"]), esc(g["name"]), esc(g["status"]), esc(g["clears_when"]), esc(g["current"])] for g in model["gates"]]
    slot_html = f"""
<section><h2>Rules</h2>{table(["ID", "Rule", "Why"], rules)}</section>
<section><h2>Gates</h2>{table(["ID", "Gate", "Status", "Clears when", "Current"], gates)}</section>
<section><h2>Store</h2><p>{len(model['store']['slots'])} slot rows. {esc(model['store']['note'])}</p></section>"""
    (OUT / "slot-model.html").write_text(page("Depth slot model", slot_html, "Slot model"))

    frows = [[esc(f["id"]), esc(f["area"]), esc(f["item"]), esc(f["action"]), esc(f["status"]), link(f["source"])]
             for f in flags["flags"]]
    flag_html = f"""
<section><p>Flagged for review. These items do not block the merge. Each item lists the source to check.</p>
{table(["ID", "Area", "Item", "Action", "Status", "Source"], frows)}</section>"""
    (OUT / "flags.html").write_text(page("Flagged for review — depth", flag_html, "Flagged for review"))

    print("built depth/index.html, depth/route-census.html, depth/slot-model.html, depth/flags.html")


if __name__ == "__main__":
    main()
